// Real Tauri WebView regression on the owned xunchuan-overview isolated identity.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';
const shots = path.resolve('.tmp/shots/overview-select');
fs.mkdirSync(shots, { recursive: true });
const report = { checks: [], pageerrors: [], consoleErrors: [], shots: [] };
const check = (name, passed, detail) => { report.checks.push({ name, passed: Boolean(passed), detail }); assert.ok(passed, `${name}: ${JSON.stringify(detail)}`); };
let browser;
try {
  browser = await chromium.connectOverCDP('http://127.0.0.1:9387');
  const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('http://127.0.0.1:1487'));
  assert.ok(page, 'Owned native WebView is not running');
  page.setDefaultTimeout(25000);
  page.on('pageerror', error => report.pageerrors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') report.consoleErrors.push(message.text()); });
  await page.reload();
  await page.getByText('原生已核验', { exact: false }).waitFor();
  const paths = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('get_aster_paths'));
  check('native isolated test library', paths.root.includes('app.aster.research.dev.xunchuan-overview.'), paths.root);
  if (await page.locator('.reader-scene-shell').filter({ visible: true }).count()) await page.getByRole('button', { name: '返回场景' }).click();
  if (!await page.locator('.library-paper-index tbody tr:visible').count()) {
    const listTab = page.getByRole('button', { name: '列表', exact: true });
    if (await listTab.isVisible()) await listTab.click();
    else await page.getByRole('button', { name: '文献库', exact: true }).first().click();
  }
  const list = page.locator('.library-paper-index tbody tr').first();
  await list.waitFor();
  await list.click({ position: { x: 160, y: 20 } });
  const listPaperId = await list.evaluate(el => el.querySelector('.paper-index-title')?.textContent?.trim());
  check('list row selected without checking its bulk checkbox', (await list.getAttribute('class'))?.includes('selected') && !(await list.locator('input[type=checkbox]').isChecked()), listPaperId);
  const listStyle = await list.evaluate(el => ({ background: getComputedStyle(el.querySelector('td')).backgroundColor, bar: getComputedStyle(el.querySelector('td')).boxShadow }));
  const shot = async name => { await page.getByText('原生已核验', { exact: false }).waitFor(); await page.screenshot({ path: path.join(shots, `${name}.png`) }); report.shots.push(name); };
  await shot('after-list-selected-light');
  await page.getByRole('button', { name: '综览', exact: true }).click();
  const row = page.locator('.summary-row').first();
  await row.waitFor();
  const rowStyle = () => row.evaluate(el => ({ background: getComputedStyle(el).backgroundColor, pinned: getComputedStyle(el.querySelector('.summary-pinned')).backgroundColor, bar: getComputedStyle(el.querySelector('.summary-pinned')).boxShadow }));
  const light = await rowStyle();
  check('same active identity across list and overview', (await row.innerText()).includes(listPaperId) && await row.getAttribute('aria-current') === 'true' && !(await row.locator('input[type=checkbox]').isChecked()), light);
  check('same green fill and edge as list, continuous through pinned column', light.background === listStyle.background && light.pinned === light.background && light.bar.includes('69, 184, 121') && listStyle.bar.includes('69, 184, 121'), { listStyle, light });
  await shot('after-overview-current-light');
  await row.locator('input[type=checkbox]').check();
  check('bulk checkbox does not change active paper or open reader', await row.getAttribute('aria-current') === 'true' && (await row.getAttribute('class')).includes('bulk-selected') && (await row.getAttribute('class')).includes('current') && !(await page.locator('.reader-scene-shell').filter({ visible: true }).count()));
  await shot('after-overview-bulk-plus-current');
  await row.locator('input[type=checkbox]').uncheck();
  check('unchecking bulk keeps current paper', await row.getAttribute('aria-current') === 'true' && !(await row.getAttribute('class')).includes('bulk-selected'));
  await row.locator('.summary-cell').first().click();
  check('clicking blank summary cell activates current paper without opening reader', await row.getAttribute('aria-current') === 'true' && !(await page.locator('.reader-scene-shell').filter({ visible: true }).count()));
  const viewport = page.locator('.summary-viewport');
  await viewport.focus(); await page.keyboard.press('ArrowDown');
  check('keyboard navigation keeps current paper and leaves bulk unchecked', await row.getAttribute('aria-current') === 'true' && !(await row.locator('input[type=checkbox]').isChecked()));
  for (let i = 0; i < 5; i++) await page.getByRole('button', { name: '放大综览' }).click();
  await page.waitForFunction(() => document.querySelector('.summary-zoom button:nth-child(2)')?.textContent?.includes('150%'));
  check('overview at 150 percent still has uninterrupted active row', (await rowStyle()).background === (await rowStyle()).pinned);
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setDeviceMetricsOverride', { width: 980, height: 800, deviceScaleFactor: 0, mobile: false });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'midnight'; });
  await page.waitForTimeout(400);
  const dark = await rowStyle();
  check('dark theme 150 percent uses matched pinned/background and semantic accent', dark.background === dark.pinned && dark.background !== light.background && dark.bar.includes('145, 182, 154'), dark);
  await shot('after-overview-current-dark-150pct');
  if (!(await viewport.getAttribute('class')).includes('title-pinned')) await page.getByRole('button', { name: '固定标题列', exact: true }).click();
  await viewport.evaluate(el => { el.scrollLeft = 260; });
  await page.waitForTimeout(120);
  const pinned = await row.evaluate(el => ({ pinned: el.querySelector('.summary-pinned').getBoundingClientRect().left, viewport: el.closest('.summary-viewport').getBoundingClientRect().left, scrollLeft: el.closest('.summary-viewport').scrollLeft, bar: getComputedStyle(el.querySelector('.summary-pinned')).boxShadow }));
  check('horizontal scroll keeps green left edge on sticky title column', pinned.scrollLeft > 0 && Math.abs(pinned.pinned - pinned.viewport) <= 4 && pinned.bar.includes('145, 182, 154'), pinned);
  await shot('after-overview-horizontal-pinned');
  await cdp.send('Emulation.clearDeviceMetricsOverride');
  await page.evaluate(() => { document.documentElement.dataset.theme = 'paper'; });
  await viewport.focus(); await page.keyboard.press('Enter');
  await page.locator('.reader-scene-shell').filter({ visible: true }).waitFor();
  check('Enter on active overview opens current paper', !!await page.locator('.reader-scene-shell').filter({ visible: true }).count());
  check('no page errors', report.pageerrors.length === 0, report.pageerrors);
  check('no console errors', report.consoleErrors.length === 0, report.consoleErrors);
  console.log(JSON.stringify({ passed: report.checks.length, shots: report.shots, pageerrors: report.pageerrors, consoleErrors: report.consoleErrors }));
} finally {
  fs.writeFileSync(path.join(shots, 'after-result.json'), JSON.stringify(report, null, 2));
  await browser?.close();
}

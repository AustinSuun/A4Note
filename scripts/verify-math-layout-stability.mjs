import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const { EditorState } = require('@codemirror/state');
const path = 'src/features/explorer/mathLayoutStability.ts';
const source = fs.readFileSync(path, 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } });
const mod = { exports: {} };
vm.runInThisContext(`(function(require,module,exports){${compiled.outputText}\n})`, { filename: path })(require, mod, mod.exports);
const { mathSizes, mathSizesChanged, mathAttributes, mathBlockSize, mathLineHeight } = mod.exports;
const doc = 'START\n\n$$\\sum_{i=1}^{n}i$$\n\nInline $x^2$ tail\n\nEND';
const from = doc.indexOf('$$'), to = doc.lastIndexOf('$$') + 2;
const line = doc.indexOf('Inline');
let state = EditorState.create({ doc, extensions: [mathSizes] });
assert.equal(mathBlockSize(state, from), undefined);
const block = { height: 92, sourceHeight: 36, to, text: doc.slice(from, to) };
state = state.update({ effects: mathSizesChanged.of({ signature: 'width|font', blocks: new Map([[from, block]]), lines: new Map([[line, 42]]) }) }).state;
assert.equal(state.doc.toString(), doc, 'measurement must not modify Markdown');
assert.equal(mathBlockSize(state, from).height, 92);
assert.equal(mathLineHeight(state, line), 42);
assert.deepEqual(mathAttributes(from, to, true), { 'data-math-from': String(from), 'data-math-to': String(to), 'data-math-display': 'true' });
const selected = state.update({ selection: { anchor: from + 2 } }).state;
assert.equal(mathBlockSize(selected, from).height, 92, 'selection must keep the same reservation');
const shifted = state.update({ changes: { from: 0, insert: 'New\n' } }).state;
assert.equal(mathBlockSize(shifted, from + 4).to, to + 4, 'unrelated edits map block boundaries');
assert.equal(mathLineHeight(shifted, line + 4), 42, 'unrelated edits preserve inline heights immediately');
const edited = shifted.update({ changes: { from: from + 6, to: to + 2, insert: 'x' } }).state;
assert.equal(edited.field(mathSizes).blocks.size, 0, 'changed formula must not retain old size');
const inlineEdit = state.update({ changes: { from: line + 8, insert: 'longer' } }).state;
assert.equal(inlineEdit.field(mathSizes).lines.size, 0, 'changed source line must be remeasured');
assert.equal(mathBlockSize(inlineEdit, from).height, 92, 'another line must not collapse');
const deleted = state.update({ changes: { from, to } }).state;
assert.equal(deleted.field(mathSizes).blocks.size, 0);
const resized = state.update({ effects: mathSizesChanged.of({ signature: 'new width', blocks: new Map([[from, { ...block, height: 48 }]]), lines: new Map() }) }).state;
assert.equal(mathBlockSize(resized, from).height, 48, 'reservation can shrink; no permanent high-water mark');
assert.equal(mathLineHeight(resized, line), undefined);
const editor = fs.readFileSync('src/features/explorer/MarkdownLivePreviewEditor.tsx', 'utf8');
assert.match(editor, /mathLayoutStability\(createMathElement\)/);
assert.match(editor, /inclusive: wholeLines, block: true/);
assert.match(editor, /element\.style\.contain = 'inline-size'/);
assert.match(editor, /size\.height - size\.sourceHeight/);
assert.match(source, /queueMicrotask/);
assert.match(source, /this\.view\.state !== result\.state/);
assert.match(source, /removeEventListener\('loadingdone', this\.fontLoaded\)/);
console.log('PASS math layout state: text invariant, selection, range mapping, unrelated edits, invalidation, deletion, resize shrink, editor/measurement wiring');

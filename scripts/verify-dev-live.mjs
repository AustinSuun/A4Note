import assert from 'node:assert/strict';
import { liveDevPlan, liveTauriConfig } from './dev-live-config.mjs';

const first = liveDevPlan('/work/aster');
const same = liveDevPlan('/work/aster');
const other = liveDevPlan('/work/another-worktree');
const second = liveDevPlan('/work/aster', { instance: 'reader', port: 1422, cdpPort: 9231 });
assert.deepEqual(first, same);
assert.notEqual(first.identifier, 'app.aster.research');
assert.notEqual(first.identifier, other.identifier);
assert.notEqual(first.identifier, second.identifier);
assert.notEqual(first.profileDir, second.profileDir);
assert.notEqual(first.cargoTargetDir, second.cargoTargetDir);
assert.equal(first.url, 'http://127.0.0.1:1421');
for (const instance of ['../prod', '', 'x/y', 'x y', 'A', 'x'.repeat(25)]) assert.throws(() => liveDevPlan('/work/aster', { instance }));
for (const port of [0, 1023, 65536, 3.14, NaN]) assert.throws(() => liveDevPlan('/work/aster', { port }));
assert.throws(() => liveDevPlan('/work/aster', { port: 9230, cdpPort: 9230 }));
const base = { identifier: 'app.aster.research', app: { windows: [{ title: 'Original', width: 1280 }] } };
const config = liveTauriConfig(base, first);
assert.equal(config.identifier, first.identifier);
assert.equal(config.build.beforeDevCommand, null);
assert.equal(config.build.devUrl, first.url);
assert.equal(config.app.windows[0].label, 'main');
assert.equal(config.app.windows[0].width, 1280);
assert.equal(config.app.windows[0].dataDirectory, 'live-webview');
assert.equal(config.app.windows[0].devtools, true);
assert.deepEqual(config.plugins.updater.endpoints, []);
assert.equal(base.identifier, 'app.aster.research');
assert.equal(base.app.windows[0].title, 'Original');
assert.throws(() => liveTauriConfig({ app: { windows: [] } }, first));
console.log('Live development plan isolation/configuration tests passed. Runtime paths must still be checked after launch.');

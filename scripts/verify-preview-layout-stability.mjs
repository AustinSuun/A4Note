import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const { EditorState } = require('@codemirror/state');
const { history, undo, undoDepth } = require('@codemirror/commands');
const path = 'src/features/explorer/previewLayoutStability.ts';
const source = fs.readFileSync(path, 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } });
const math = { exports: {} };
const mathPath = 'src/features/explorer/mathLayoutStability.ts';
const compiledMath = ts.transpileModule(fs.readFileSync(mathPath, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } });
vm.runInThisContext(`(function(require,module,exports){${compiledMath.outputText}\n})`, { filename: mathPath })(require, math, math.exports);
const mod = { exports: {} };
vm.runInThisContext(`(function(require,module,exports){${compiled.outputText}\n})`, { filename: path })((id) => id === './mathLayoutStability' ? math.exports : require(id), mod, mod.exports);
const { previewSizes, previewSizesChanged, previewBlockAttributes, previewBlockSize, previewLineHeight } = mod.exports;
const doc = 'START\n\n| a | b |\n| --- | --- |\n| x | y |\n\n[link](https://example.com)\n\nEND';
const from = doc.indexOf('|'), to = doc.indexOf('\n\n[link]'), line = doc.indexOf('[link]');
let state = EditorState.create({ doc, extensions: [previewSizes, history()] });
assert.equal(previewBlockSize(state, from), undefined);
assert.equal(previewLineHeight(state, line), 0);
const block = { height: 120, lines: [40, 40, 40], to, text: doc.slice(from, to) };
state = state.update({ effects: previewSizesChanged.of({ signature: 'width|font', blocks: new Map([[from, block]]), lines: new Map([[line, { height: 60, contentKey: '' }]]) }) }).state;
assert.equal(state.doc.toString(), doc);
assert.equal(undoDepth(state), 0, 'measurement effects are not text history');
assert.deepEqual(previewBlockAttributes(from, to), { 'data-preview-block-from': String(from), 'data-preview-block-to': String(to) });
assert.equal(previewBlockSize(state, from).height, 120);
assert.equal(previewLineHeight(state, line), 60);
const selected = state.update({ selection: { anchor: from + 2 } }).state;
assert.equal(previewBlockSize(selected, from).height, 120);
assert.equal(previewLineHeight(selected, line), 60);
const shifted = state.update({ changes: { from: 0, insert: 'New\n' } }).state;
assert.equal(previewBlockSize(shifted, from + 4).to, to + 4);
assert.equal(previewLineHeight(shifted, line + 4), 60);
const edited = state.update({ changes: { from: from + 2, insert: 'longer cell' } }).state;
assert.equal(edited.field(previewSizes).blocks.size, 0);
assert.equal(edited.field(previewSizes).lines.size, 1);
const linkEdited = state.update({ changes: { from: line + 2, insert: 'longer label' } }).state;
assert.equal(linkEdited.field(previewSizes).lines.size, 0);
assert.equal(previewBlockSize(linkEdited, from).height, 120);
assert.equal(state.update({ changes: { from, to } }).state.field(previewSizes).blocks.size, 0);
const resized = state.update({ effects: previewSizesChanged.of({ signature: 'new width', blocks: new Map([[from, { ...block, height: 90, lines: [30, 30, 30] }]]), lines: new Map() }) }).state;
assert.equal(previewBlockSize(resized, from).height, 90, 'reservation can shrink, not a permanent high-water mark');
assert.equal(previewLineHeight(resized, line), 0);
let undoState = edited;
assert.equal(undo({ state: undoState, dispatch: tr => { undoState = tr.state; } }), true);
assert.equal(undoState.doc.toString(), doc);
const editor = fs.readFileSync('src/features/explorer/MarkdownLivePreviewEditor.tsx', 'utf8');
assert.match(editor, /previewLayoutStability\(createMeasurementDecorations\)/);
assert.match(editor, /new TableWidget\(region\), inclusive: true, block: true/);
assert.match(editor, /copy\.removeAttribute\('src'\)/);
assert.match(editor, /previewMeasureHighlight: true/);
const field = editor.slice(editor.indexOf('function createDecorationsField'), editor.indexOf('function unfoldFoldsAtEditedBoundaries'));
assert.doesNotMatch(field, /previewSizesChanged/, 'size updates must not recreate focused image widgets');
assert.match(source, /view\.dom\.append\(this\.sheet\)/);
assert.match(source, /this\.view\.state !== result\.state/);
assert.match(source, /removeEventListener\('loadingdone', this\.fontLoaded\)/);
console.log('PASS preview layout state: text/history invariance, selection, mapped lines/tables, invalidation/deletion, shrinking, undo, scoped non-remounting integration. Browser geometry is verified separately.');
